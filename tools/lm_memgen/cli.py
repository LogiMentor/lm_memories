"""Command line wrapper generator for lm_memories."""

from __future__ import annotations

import argparse
import re
from pathlib import Path
from typing import Iterable


RAM_PORTS = (
  "crw_crw",
  "rw_rw",
  "cr_cw",
  "cr_cw_ratio",
  "crw_cr",
  "crw_cw",
  "r_w",
  "r_w_ratio",
)

VENDORS = ("generic", "xilinx", "amd", "intel", "altera", "lattice", "microchip", "microsemi")
STYLES = ("auto", "distributed", "bram", "uram", "registers")
MODES = ("generic", "fixed")


def _positive_int(value: str) -> int:
  parsed = int(value, 10)
  if parsed <= 0:
    raise argparse.ArgumentTypeError("value must be positive")
  return parsed


def _latency(value: str) -> int:
  parsed = _positive_int(value)
  if parsed not in (1, 2):
    raise argparse.ArgumentTypeError("latency must be 1 or 2")
  return parsed


def _is_power_of_two(value: int) -> bool:
  return value > 0 and (value & (value - 1)) == 0


def _entity_name(path: Path) -> str:
  name = re.sub(r"[^a-z0-9_]+", "_", path.stem.lower()).strip("_")
  if not name:
    name = "lm_mem_generated"
  if name[0].isdigit():
    name = "lm_" + name
  return name


def _write(path: Path, text: str) -> None:
  path.parent.mkdir(parents=True, exist_ok=True)
  path.write_text(text, encoding="utf-8")


def _header(module_name: str, description: str) -> str:
  return f"""--=============================================================================
-- Module Name : {module_name}
-- Library     : -
-- Project     : lm_memories
-- Company     : LogiMentor Srl
-------------------------------------------------------------------------------
-- Description:
--  {description}
--  Generated by lm_memgen. Edit the generator inputs rather than this wrapper.
-------------------------------------------------------------------------------
"""


def _generic_block(mode: str, lines: Iterable[str]) -> str:
  if mode != "generic":
    return ""

  joined = ";\n".join(f"    {line}" for line in lines)
  return f"  generic(\n{joined}\n  );\n"


def _ram_expr(args: argparse.Namespace) -> dict[str, str]:
  width_b = args.width_b if args.width_b is not None else args.width_a
  if args.mode == "generic":
    return {
      "width_a": "g_width_a",
      "width_b": "g_width_b",
      "depth_a": "g_depth_a",
      "latency_a": "g_read_latency_a",
      "latency_b": "g_read_latency_b",
    }

  return {
    "width_a": str(args.width_a),
    "width_b": str(width_b),
    "depth_a": str(args.depth_a),
    "latency_a": str(args.read_latency_a),
    "latency_b": str(args.read_latency_b),
  }


def _addr_a(expr: dict[str, str]) -> str:
  return f"f_ceil_log2({expr['depth_a']}) - 1 downto 0"


def _addr_b_ratio(expr: dict[str, str]) -> str:
  return f"f_ceil_log2(({expr['depth_a']} * {expr['width_a']}) / {expr['width_b']}) - 1 downto 0"


def _ram_port_block(ports: str, expr: dict[str, str]) -> str:
  width = expr["width_a"]
  width_b = expr["width_b"]

  if ports == "crw_crw":
    return f"""  port(
    clk_a_i     : in  std_logic;
    clk_b_i     : in  std_logic;
    ena_i       : in  std_logic := '1';
    enb_i       : in  std_logic := '1';
    wen_a_i     : in  std_logic;
    wen_b_i     : in  std_logic;
    data_wr_a_i : in  std_logic_vector({width} - 1 downto 0);
    data_wr_b_i : in  std_logic_vector({width_b} - 1 downto 0);
    addr_a_i    : in  std_logic_vector({_addr_a(expr)});
    addr_b_i    : in  std_logic_vector({_addr_b_ratio(expr)});
    data_rd_a_o : out std_logic_vector({width} - 1 downto 0);
    data_rd_b_o : out std_logic_vector({width_b} - 1 downto 0)
  );
"""

  if ports == "rw_rw":
    return f"""  port(
    clk_i      : in  std_logic;
    ena_i      : in  std_logic := '1';
    enb_i      : in  std_logic := '1';
    wen_a_i    : in  std_logic;
    wen_b_i    : in  std_logic;
    wr_dat_a_i : in  std_logic_vector({width} - 1 downto 0);
    wr_dat_b_i : in  std_logic_vector({width} - 1 downto 0);
    addr_a_i   : in  std_logic_vector({_addr_a(expr)});
    addr_b_i   : in  std_logic_vector({_addr_a(expr)});
    rd_dat_a_o : out std_logic_vector({width} - 1 downto 0);
    rd_dat_b_o : out std_logic_vector({width} - 1 downto 0)
  );
"""

  if ports in ("cr_cw", "cr_cw_ratio"):
    rd_width = width_b if ports.endswith("_ratio") else width
    rd_addr = _addr_b_ratio(expr) if ports.endswith("_ratio") else _addr_a(expr)
    return f"""  port(
    wr_clk_i  : in  std_logic;
    rd_clk_i  : in  std_logic;
    ena_i     : in  std_logic := '1';
    enb_i     : in  std_logic := '1';
    wen_i     : in  std_logic;
    wr_addr_i : in  std_logic_vector({_addr_a(expr)});
    wr_dat_i  : in  std_logic_vector({width} - 1 downto 0);
    rd_addr_i : in  std_logic_vector({rd_addr});
    rd_dat_o  : out std_logic_vector({rd_width} - 1 downto 0)
  );
"""

  if ports == "crw_cr":
    return f"""  port(
    clk_a_i     : in  std_logic;
    clk_b_i     : in  std_logic;
    ena_i       : in  std_logic := '1';
    enb_i       : in  std_logic := '1';
    wen_a_i     : in  std_logic;
    data_wr_a_i : in  std_logic_vector({width} - 1 downto 0);
    addr_a_i    : in  std_logic_vector({_addr_a(expr)});
    addr_b_i    : in  std_logic_vector({_addr_a(expr)});
    data_rd_a_o : out std_logic_vector({width} - 1 downto 0);
    data_rd_b_o : out std_logic_vector({width} - 1 downto 0)
  );
"""

  if ports == "crw_cw":
    return f"""  port(
    clk_a_i     : in  std_logic;
    clk_b_i     : in  std_logic;
    ena_i       : in  std_logic := '1';
    enb_i       : in  std_logic := '1';
    wen_a_i     : in  std_logic;
    wen_b_i     : in  std_logic;
    data_wr_a_i : in  std_logic_vector({width} - 1 downto 0);
    data_wr_b_i : in  std_logic_vector({width} - 1 downto 0);
    addr_a_i    : in  std_logic_vector({_addr_a(expr)});
    addr_b_i    : in  std_logic_vector({_addr_a(expr)});
    data_rd_a_o : out std_logic_vector({width} - 1 downto 0)
  );
"""

  rd_width = width_b if ports == "r_w_ratio" else width
  rd_addr = _addr_b_ratio(expr) if ports == "r_w_ratio" else _addr_a(expr)
  return f"""  port(
    clk_i     : in  std_logic;
    ena_i     : in  std_logic := '1';
    enb_i     : in  std_logic := '1';
    wen_i     : in  std_logic;
    wr_addr_i : in  std_logic_vector({_addr_a(expr)});
    wr_dat_i  : in  std_logic_vector({width} - 1 downto 0);
    rd_addr_i : in  std_logic_vector({rd_addr});
    rd_dat_o  : out std_logic_vector({rd_width} - 1 downto 0)
  );
"""


