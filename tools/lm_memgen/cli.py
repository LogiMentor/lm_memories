def _validate_ram(args: argparse.Namespace, parser: argparse.ArgumentParser) -> None:
  width_b = args.width_b if args.width_b is not None else args.width_a
  min_width = min(args.width_a, width_b)
  max_width = max(args.width_a, width_b)
  ratio_ports = {"crw_crw", "cr_cw_ratio", "r_w_ratio"}

  if max_width % min_width != 0:
    parser.error("--width-a and --width-b must have an integer ratio")
  if (args.depth_a * args.width_a) % width_b != 0:
    parser.error("--depth-a * --width-a must divide cleanly by --width-b")
  if args.ports not in ratio_ports and width_b != args.width_a:
    parser.error(f"--ports {args.ports} requires --width-b to match --width-a")
  if args.ports not in ratio_ports and args.read_latency_b != args.read_latency_a:
    parser.error(f"--ports {args.ports} uses one latency; set both read latencies equal")


def _render_ram(args: argparse.Namespace) -> str:
  out = Path(args.out)
  entity = _entity_name(out)
  expr = _ram_expr(args)
  width_b = args.width_b if args.width_b is not None else args.width_a
  generic_lines = (
    f"g_width_a        : positive := {args.width_a}",
    f"g_depth_a        : positive := {args.depth_a}",
    f"g_width_b        : positive := {width_b}",
    f"g_read_latency_a : positive := {args.read_latency_a}",
    f"g_read_latency_b : positive := {args.read_latency_b}",
  )

  return (
    _header(entity, f"Wrapper around lm_mem_ram_{args.ports}.")
    + "\nlibrary ieee;\nuse ieee.std_logic_1164.all;\n\nuse work.lm_mem_pkg.all;\n\n"
    + f"entity {entity} is\n"
    + _generic_block(args.mode, generic_lines)
    + _ram_port_block(args.ports, expr)
    + f"end entity {entity};\n\n"
    + f"architecture a_rtl of {entity} is\n"
    + "begin\n"
    + _ram_instance(args.ports, expr)
    + "end architecture a_rtl;\n"
  )


def _render_fifo(args: argparse.Namespace) -> str:
  out = Path(args.out)
  entity = _entity_name(out)
  if args.mode == "generic":
    width = "g_width"
    depth = "g_depth"
    generic = _generic_block(
      args.mode,
      (
        f"g_width : positive := {args.width}",
        f"g_depth : positive := {args.depth}",
      ),
    )
  else:
    width = str(args.width)
    depth = str(args.depth)
    generic = ""

  return f"""{_header(entity, "Wrapper around lm_mem_fifo_sync.")}
library ieee;
use ieee.std_logic_1164.all;

entity {entity} is
{generic}  port(
    clk_i          : in  std_logic;
    rst_n_i        : in  std_logic;
    din_i          : in  std_logic_vector({width} - 1 downto 0);
    wen_i          : in  std_logic;
    ren_i          : in  std_logic;
    dout_o         : out std_logic_vector({width} - 1 downto 0);
    full_o         : out std_logic;
    almost_full_o  : out std_logic;
    empty_o        : out std_logic;
    almost_empty_o : out std_logic;
    valid_o        : out std_logic
  );
end entity {entity};

architecture a_rtl of {entity} is
begin
  inst_fifo : entity work.lm_mem_fifo_sync
    generic map(
      g_data_w             => {width},
      g_depth              => {depth},
      g_almost_empty_limit => 1,
      g_almost_full_limit  => 1
    )
    port map(
      clk_i          => clk_i,
      rst_n_i        => rst_n_i,
      din_i          => din_i,
      wen_i          => wen_i,
      ren_i          => ren_i,
      dout_o         => dout_o,
      full_o         => full_o,
      almost_full_o  => almost_full_o,
      empty_o        => empty_o,
      almost_empty_o => almost_empty_o,
      valid_o        => valid_o
    );
end architecture a_rtl;
"""


def _add_ram_parser(subparsers: argparse._SubParsersAction[argparse.ArgumentParser]) -> None:
  parser = subparsers.add_parser("ram", help="emit a RAM wrapper")
  parser.add_argument("--ports", choices=RAM_PORTS, required=True, help="RAM port topology")
  parser.add_argument("--vendor", choices=VENDORS, default="generic", help="target vendor annotation")
  parser.add_argument("--family", default="generic", help="target family annotation")
  parser.add_argument("--tool", default="generic", help="target synthesis tool annotation")
  parser.add_argument("--width-a", type=_positive_int, required=True, help="port A data width")
  parser.add_argument("--depth-a", type=_positive_int, required=True, help="port A depth")
  parser.add_argument("--width-b", type=_positive_int, help="port B data width")
  parser.add_argument("--read-latency-a", type=_latency, default=1, help="port A read latency")
  parser.add_argument("--read-latency-b", type=_latency, default=1, help="port B read latency")
  parser.add_argument("--style", choices=STYLES, default="auto", help="requested memory style annotation")
  parser.add_argument("--mode", choices=MODES, default="generic", help="wrapper generation mode")
  parser.add_argument("--out", required=True, help="output VHDL file")
  parser.set_defaults(func=_run_ram, parser=parser)


def _add_fifo_parser(subparsers: argparse._SubParsersAction[argparse.ArgumentParser]) -> None:
  parser = subparsers.add_parser("fifo", help="emit a FIFO wrapper")
  parser.add_argument("--vendor", choices=VENDORS, default="generic", help="target vendor annotation")
  parser.add_argument("--width", type=_positive_int, required=True, help="FIFO data width")
  parser.add_argument("--depth", type=_positive_int, required=True, help="FIFO depth")
  parser.add_argument("--clocking", choices=("sync",), default="sync", help="FIFO clocking mode")
  parser.add_argument("--mode", choices=MODES, default="generic", help="wrapper generation mode")
  parser.add_argument("--out", required=True, help="output VHDL file")
  parser.set_defaults(func=_run_fifo, parser=parser)


def _run_ram(args: argparse.Namespace) -> int:
  _validate_ram(args, args.parser)
  _write(Path(args.out), _render_ram(args))
  return 0


def _run_fifo(args: argparse.Namespace) -> int:
  if not _is_power_of_two(args.depth):
    args.parser.error("--depth must be a power of two for lm_mem_fifo_sync")
  _write(Path(args.out), _render_fifo(args))
  return 0


def build_parser() -> argparse.ArgumentParser:
  parser = argparse.ArgumentParser(
    prog="lm_memgen",
    description="Generate lm_memories VHDL wrappers.",
  )
  subparsers = parser.add_subparsers(dest="command", required=True)
  _add_ram_parser(subparsers)
  _add_fifo_parser(subparsers)
  return parser


def main(argv: list[str] | None = None) -> int:
  parser = build_parser()
  args = parser.parse_args(argv)
  return args.func(args)
